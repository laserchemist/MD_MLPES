"""
build_deck.py — assemble the self-contained talk page for GitHub Pages.

Reads ``talk/deck_source.html``, replaces every ``<!--FIG:name-->`` marker
with the SVG from ``talk/figures/name.svg`` (inlined, so the slide fonts
apply to figure text and the page is one file), and writes
``talk/index.html``.

Usage
-----
    python3 talk/scripts/make_figures.py   # (re)draw figures from outputs/
    python3 talk/scripts/build_deck.py     # inline them into index.html

Options: ``--source``, ``--figures``, ``--output`` override the defaults.
"""

from __future__ import annotations

import argparse
import re
from itertools import count
from pathlib import Path

TALK_DIR = Path(__file__).resolve().parents[1]
MARKER = re.compile(r"<!--FIG:([A-Za-z0-9_\-]+)-->")
_uid = count(1)


def clean_svg(svg_text: str, prefix: str) -> str:
    """Prepare one SVG file for inlining in HTML.

    * drops the XML declaration, DOCTYPE and comments;
    * removes fixed width/height on the root <svg> so CSS sizes it
      (the viewBox keeps the aspect ratio);
    * prefixes every ``id`` (and its ``#id`` / ``url(#id)`` references) with
      ``prefix`` so ids from different figures can never collide.
    """
    s = re.sub(r"<\?xml[^>]*\?>", "", svg_text)
    s = re.sub(r"<!DOCTYPE[^>]*>", "", s, flags=re.S)
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    start = s.find("<svg")
    if start < 0:
        raise ValueError("no <svg> element found")
    s = s[start:].strip()
    root_end = s.find(">")
    root = s[:root_end]
    root = re.sub(r'\s(width|height)="[^"]*"', "", root)
    s = root + s[root_end:]
    ids = set(re.findall(r'\sid="([^"]+)"', s))
    for i in sorted(ids, key=len, reverse=True):
        new = f"{prefix}-{i}"
        s = s.replace(f'id="{i}"', f'id="{new}"')
        s = s.replace(f"url(#{i})", f"url(#{new})")
        s = s.replace(f'href="#{i}"', f'href="#{new}"')
    return s


def build(source: Path, figures: Path, output: Path) -> list[str]:
    """Inline all figures into ``source`` and write ``output``.

    Returns the list of figure names inlined, in order. Raises
    FileNotFoundError naming any marker whose SVG is missing.
    """
    html = source.read_text(encoding="utf-8")
    used: list[str] = []

    def repl(m: re.Match) -> str:
        name = m.group(1)
        path = figures / f"{name}.svg"
        if not path.exists():
            raise FileNotFoundError(
                f"Figure '{name}' referenced in {source.name} but {path} "
                "is missing. Run make_figures.py first.")
        used.append(name)
        svg = clean_svg(path.read_text(encoding="utf-8"), f"f{next(_uid)}")
        return svg.replace("<svg", f'<svg role="img" aria-label="{name}"', 1)

    html = MARKER.sub(repl, html)
    html = html.replace(
        "<!-- SOURCE FILE.", "<!-- GENERATED by talk/scripts/build_deck.py; "
        "edit deck_source.html instead.", 1)
    output.write_text(html, encoding="utf-8")
    return used


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--source", type=Path, default=TALK_DIR / "deck_source.html")
    ap.add_argument("--figures", type=Path, default=TALK_DIR / "figures")
    ap.add_argument("--output", type=Path, default=TALK_DIR / "index.html")
    a = ap.parse_args()
    used = build(a.source, a.figures, a.output)
    n_slides = a.output.read_text(encoding="utf-8").count("<section")
    kb = a.output.stat().st_size / 1024
    print(f"Wrote {a.output} — {n_slides} slides, {len(used)} figures, {kb:.0f} KB")


if __name__ == "__main__":
    main()
